export const MOCK_FLIGHTS: Flight[] = seeds.map(
  ([
    id,
    callsign,
    airline,
    aircraft,
    from,
    to,
    status,
    departure,
    arrival,
    progress,
    delayMinutes = 0,
  ]) => {
    const origin = AIRPORTS.find((a) => a.code === from)!;
    const destination = AIRPORTS.find((a) => a.code === to)!;
    return {
      id,
      callsign,
      airline,
      aircraft,
      origin,
      destination,
      status,
      departure,
      arrival,
      progress,
      delayMinutes,
      position: [
        origin.position[0] + (destination.position[0] - origin.position[0]) * progress,
        origin.position[1] + (destination.position[1] - origin.position[1]) * progress,
      ],
      altitude: status === 'En Route' ? 34000 : 0,
      speed: status === 'En Route' ? 462 : 0,
    };
  },
);
